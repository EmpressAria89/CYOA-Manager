const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src-tauri/src/viewer_presentation.js','utf8');
const context={window:{addEventListener(){}},document:{readyState:'loading',addEventListener(){}},requestAnimationFrame(){}};
vm.runInNewContext(source,context);
const visible=context.window.__cyoaManagerPresentation.rowVisible;
const req=id=>({type:'id',required:true,reqId:id,more:[]});
const nav={id:'nav',requireds:[]},race={id:'races',requireds:[req('racesTab')]},child={id:'dragon',requireds:[req('dragonKin')]},grandchild={id:'dragonBonus',requireds:[req('dragonColor')]};
const owners={racesTab:nav,dragonKin:race,dragonColor:child};let open=false;
const check=reqs=>reqs.every(r=>r.reqId!=='racesTab'||open);
assert.equal(visible(child,check,id=>owners[id]),false);
assert.equal(visible(grandchild,check,id=>owners[id]),false);
open=true;assert.equal(visible(child,check,id=>owners[id]),true);
assert.equal(visible(race,check,id=>owners[id]),true);
assert.equal(visible({id:'unknown',requireds:[req('unknown')]},check,id=>owners[id]),true);
assert.equal(visible({id:'negative',requireds:[{...req('dragonKin'),required:false}]},()=>false,id=>owners[id]),true);
assert.equal(visible({id:'or',requireds:[{...req('dragonKin'),more:[req('other')]}]},()=>false,id=>owners[id]),true);
assert.equal(visible({id:'combo',requireds:[req('dragonKin'),req('racesTab')]},()=>false,id=>owners[id]),true);
const a={id:'a',requireds:[req('b')]},b={id:'b',requireds:[req('a')]};assert.equal(visible(a,()=>true,id=>({a,b}[id])),true);
const chain=Array.from({length:100},(_,i)=>({id:String(i),requireds:[req(String(i+1))]}));assert.equal(visible(chain[0],()=>true,id=>chain[Number(id)]),true);
console.log('Section dependency checks passed');
